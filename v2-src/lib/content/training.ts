/**
 * Methods usable at `level`, best XP first.
 *
 * A method with a `maxLevel` drops out once you pass it — not because it stops
 * working, but because it has stopped being the right way to spend the hour,
 * which is the question this list answers.
 */
export function methodsFor(skill: number, level: number): TrainingMethod[] {
  const all = TRAINING[skill] ?? [];
  return all
    .filter((m) => level >= m.minLevel && (m.maxLevel === undefined || level <= m.maxLevel))
    .sort((a, b) => b.xpPerHour - a.xpPerHour);
}

/** The next meaningful threshold above `level`, or null if none remain. */
export function nextUnlock(skill: number, level: number): SkillUnlock | null {
  let best: SkillUnlock | null = null;
  for (const u of UNLOCKS) {
    if (u.skill !== skill || u.level <= level) continue;
    if (best === null || u.level < best.level) best = u;
  }
  return best;
}

/**
 * Hours of grinding between two XP values at a given rate.
 *
 * Returns Infinity for a rate of zero rather than dividing — some entries
 * (charm gathering, the XP capacitor) genuinely have no hourly rate, and a
 * silent NaN would poison every total downstream.
 */
export function timeToLevel(currentXp: number, targetXp: number, xpPerHour: number): number {
  const remaining = targetXp - currentXp;
  if (remaining <= 0) return 0;
  if (xpPerHour <= 0) return Infinity;
  return remaining / xpPerHour;
}
