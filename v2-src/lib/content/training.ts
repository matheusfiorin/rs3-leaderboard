// Training methods + unlock thresholds, per skill.
//
// Ported from the legacy tips.js / next-steps.js pair and re-verified against
// runescape.wiki in mid-2026. The legacy data was both stale and, in places,
// fabricated — "Banded iron" (Mining) and "Gnome bench" (Construction) are not
// real pages, Pack yak was listed at 67 instead of 96, and Sinkholes were
// described as weekly when they reset daily. Everything below is checked
// against a live wiki page that actually exists.
//
// Two things the legacy DB missed entirely and that this app exists to cover:
//   1. The 99-120 / 99-110 bands. RS3 raised the artisan and gathering caps to
//      110 and several support skills to 120, and there is a whole tier-100+
//      content wave (primal ore, eternal magic trees, starbloom, eternal bows)
//      that never appears in the old file.
//   2. Realistic gp/hr on the methods where the money matters more than the XP.
//
// XP rates are per-hour at the low end of the method's band with no bonus XP,
// no avatar and no skilling outfit, unless a note says otherwise. Where the
// wiki quotes a rate "at 99", it is noted rather than silently used as the
// headline number — a rate you cannot hit for another 20 levels is a lie.

export type Intensity = "afk" | "moderate" | "click-intensive";

export interface TrainingMethod {
  id: string;
  name: string;
  /** Lowest level the method is usable at. */
  minLevel: number;
  /** Level at which the method stops being the best use of the hour. Omitted
   *  when the method stays viable to the skill cap. */
  maxLevel?: number;
  xpPerHour: number;
  /** Only set where the method is a genuine earner. Absent means "roughly
   *  break-even or a loss" — silence here is information. */
  gpPerHour?: number;
  intensity: Intensity;
  members: boolean;
  /** runescape.wiki page title. */
  wiki: string;
  note?: string;
}

export interface SkillUnlock {
  skill: number;
  level: number;
  label: string;
  blurb: string;
  wiki: string;
}

